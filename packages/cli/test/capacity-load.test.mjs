import test from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execute } from '../src/recovery/execute.mjs';
const script = fileURLToPath(new URL('../../../scripts/capacity/load.mjs', import.meta.url));
test('bounded capacity workload counts successful reads and fails on HTTP errors', async t => {
  const dir = await mkdtemp(join(tmpdir(), 'fogd-capacity-'));
  let requests = 0;
  const server = createServer((req, res) => { requests++; res.statusCode = req.url === '/ok' ? 200 : 503; res.end('fixture'); });
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await rm(dir, { recursive: true, force: true }); });
  const run = (path, file, env = process.env) => execute(process.execPath, [script, '--url', `http://127.0.0.1:${server.address().port}/${path}`, '--output', join(dir, file), '--seconds', '1', '--concurrency', '2'], { timeoutMs: 15000, env });
  await run('ok', 'ok.json');
  const ok = JSON.parse(await readFile(join(dir, 'ok.json'), 'utf8'));
  assert.equal(ok.errors, 0);
  assert.ok(ok.requests > 1 && ok.requests <= 20);
  assert.equal(ok.statuses['200'], ok.requests);
  assert.equal(ok.responseBytes, ok.requests * 7);
  const beforeRetry = requests;
  await assert.rejects(run('ok', 'ok.json'));
  assert.equal(requests, beforeRetry, 'existing output is refused before any HTTP request');
  assert.deepEqual(JSON.parse(await readFile(join(dir, 'ok.json'), 'utf8')), ok);
  await assert.rejects(run('fail', 'fail.json'));
  const fail = JSON.parse(await readFile(join(dir, 'fail.json'), 'utf8'));
  assert.equal(fail.errors, fail.requests);
  assert.equal(fail.statuses['503'], fail.requests);
  await assert.rejects(run('ok', 'insecure.json', { ...process.env, NODE_TLS_REJECT_UNAUTHORIZED: '0' }));
  await assert.rejects(readFile(join(dir, 'insecure.json')), { code: 'ENOENT' });
});
