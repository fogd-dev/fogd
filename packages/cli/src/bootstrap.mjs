import { readFile, writeFile, chmod } from 'node:fs/promises';
import { randomBytes } from 'node:crypto';
import { requireDocker, configEnv, configPath } from './local.mjs';

export async function prepareEnvironment(shared = false) {
  const env = await configEnv(), additions = {};
  requireDocker(env);
  if (shared) {
    for (const [key, value] of Object.entries({ FOGD_PROFILE: 'shared', FOGD_TLS: '1', FOGD_DEPLOY_TOKEN: '' })) {
      if (env[key] !== value) additions[key] = value;
      env[key] = value;
    }
  }
  const names = ['FOGD_ADMIN_PASSWORD', 'FOGD_GATEWAY_TOKEN'];
  if (env.FOGD_PROFILE !== 'shared') names.push('FOGD_DEPLOY_TOKEN');
  for (const name of names) {
    if (!env[name]) { env[name] = randomBytes(32).toString('hex'); additions[name] = env[name]; }
  }
  if (Object.keys(additions).length) await persistEnvironment(additions);
  return env;
}

async function persistEnvironment(values) {
  const lines = Object.entries(values).map(([key, value]) => {
    if (!/^[A-Z][A-Z0-9_]*$/.test(key) || typeof value !== 'string' || /[\r\n]/.test(value)) throw new Error('Invalid generated installation setting');
    return `${key}=${value}`;
  });
  const path = configPath(); let existing = '';
  try { existing = await readFile(path, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await writeFile(path, `${existing}\n# Generated by fogd; keep this file private.\n${lines.join('\n')}\n`, { mode: 0o600 });
  await chmod(path, 0o600);
}
