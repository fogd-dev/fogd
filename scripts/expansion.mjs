import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { readFile, access } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { X509Certificate } from 'node:crypto';
import { platformClient } from './platform-client.mjs';
import { expect } from './guestbook-browser.mjs';
import { manifest } from '../packages/runtime/src/manifest.mjs';
import { compose, stackRoot, run, buildArtifact } from '../packages/cli/src/local.mjs';
import { resolvedCompose } from '../packages/cli/src/compose/config.mjs';
import { volumeHelper } from '../packages/cli/src/recovery/volumes.mjs';
import { volumeNames, projectContainers } from '../packages/cli/src/recovery/docker.mjs';
import { verifyBundle } from '../packages/cli/src/recovery/bundle.mjs';

const exec = promisify(execFile);
const client = await platformClient(), operator = client.env;
if (operator.NODE_EXTRA_CA_CERTS) operator.NODE_EXTRA_CA_CERTS = resolve(operator.NODE_EXTRA_CA_CERTS);
const target = process.argv[2], certPath = resolve(process.argv[3]), keyPath = resolve(process.argv[4]);
assert.match(operator.COMPOSE_PROJECT_NAME || '', /^fogd-m10[a-z0-9-]*$/);
assert.match(target || '', /^fogd-m10[a-z0-9-]*$/);
assert.notEqual(target, operator.COMPOSE_PROJECT_NAME);
assert.equal(operator.FOGD_PROFILE, 'shared');
const cert = new X509Certificate(await readFile(certPath));
for (const name of ['accounts', 'replacement', 'third', 'fourth']) assert.ok(cert.checkHost(`${name}.${operator.FOGD_BASE_DOMAIN || 'localhost'}`), `Certificate must cover ${name}`);
const cli = join(stackRoot, 'packages/cli/bin/fogd.js');
const bundle = join(stackRoot, '.fogd', `${target}-source`), output = join(stackRoot, '.fogd', `${target}-config`);
for (const path of [bundle, output]) await assert.rejects(access(path), { code: 'ENOENT' });
const sourceConfig = await resolvedCompose(operator);
assert.equal(JSON.parse(sourceConfig.services.controller.environment.FOGD_SLOTS).length, 2);
const entries = await (await client.appRequest('replacement', '/api/entries')).json();
assert.equal(entries.count, 1);
assert.equal((await client.appRequest('accounts', '/')).status, 200);
const { csrf } = await client.api('/v1/admin');
const credential = await client.api('/v1/credentials', { method: 'POST', headers: { 'X-Fogd-CSRF': csrf }, body: JSON.stringify({ name: 'Expansion builder', apps: ['third', 'fourth'] }) });
const before = await client.api('/v1/admin');
await compose(['stop', 'workerd', 'controller'], operator);
await compose(['stop', ...volumeNames(sourceConfig).filter(name => name.startsWith('slot-'))], operator);
await compose(['stop', 'minio', 'bucket-init'], operator);
await run(process.execPath, [cli, 'tls', 'import', certPath, keyPath], { env: operator });
await compose(['up', '-d', '--pull', 'never'], operator);
await ready(client);
assert.deepEqual(await (await client.appRequest('replacement', '/api/entries')).json(), entries);
await run(process.execPath, [cli, 'backup', bundle], { env: operator });
const args = ['expand', bundle, '--fleets', '3', '--project', target, '--output', output];
await compose(['start', 'workerd'], operator);
try { await assert.rejects(exec(process.execPath, [cli, ...args], { env: operator, timeout: 900000 }), error => /Project still has running containers/.test(error.stderr)); }
finally { await compose(['stop', 'workerd'], operator); }
assert.equal((await projectContainers(target)).length, 0);
await assert.rejects(access(output), { code: 'ENOENT' });
await run(process.execPath, [cli, ...args], { env: operator });
assert.ok((await projectContainers(target)).every(c => !c.State.Running));
const snapshot = await verifyBundle(bundle);
for (const name of volumeNames(snapshot.config)) await volumeHelper(snapshot.manifest.images.controller, snapshot.config.volumes[name].name, ['tar', '--numeric-owner', '-C', '/data', '--compare', '-pf', '-'], { input: join(bundle, `${name}.tar`) });
console.log('PASS: expansion leaves every archived source-volume file unchanged');
const env = { ...operator, COMPOSE_PROJECT_NAME: target, FOGD_COMPOSE_FILE: join(output, 'compose.json') };
await run(process.execPath, [cli, 'up', '--shared'], { env });
const expanded = await platformClient(env); await ready(expanded);
const after = await expanded.api('/v1/admin');
assert.deepEqual(after.apps, before.apps); assert.deepEqual(after.secrets, before.secrets);
assert.deepEqual(after.credentials, before.credentials);
assert.equal(after.capacity.slots.configured, 3); assert.equal(after.capacity.slots.available, 1);
assert.deepEqual(await (await expanded.appRequest('replacement', '/api/entries')).json(), entries);
assert.equal((await expanded.appRequest('third', '/api/entries')).status, 404);
const builder = await platformClient({ ...env, FOGD_DEPLOY_TOKEN: credential.token });
const third = await builder.submit(join(stackRoot, 'examples/notebook'), 'third');
assert.equal((await expanded.appRequest('third', '/api/entries')).status, 404);
assert.equal((await expanded.decide(third)).status, 'active');
assert.deepEqual(await (await expanded.appRequest('third', '/api/entries')).json(), { entries: [], count: 0 });
const entry = { id: 'third-only', title: 'Third app', body: 'Independent third-fleet R2 bytes' };
assert.equal((await expanded.appRequest('third', '/api/entries', { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(entry) })).status, 200);
const fourthRelease = await buildArtifact(join(stackRoot, 'examples/notebook'), 'fourth');
const fourthArtifact = await manifest(fourthRelease.outputDir, fourthRelease);
await assert.rejects(expanded.api('/v1/deployments', { method: 'POST', headers: { Authorization: `Bearer ${credential.token}` }, body: JSON.stringify(fourthArtifact) }), /No available app slots/);
await compose(['restart', 'workerd', 'slot-3-a'], env);
await ready(expanded);
await expect.poll(async () => { try { return await (await expanded.appRequest('third', '/api/entries')).json(); } catch { return null; } }, { timeout: 120000 }).toEqual({ entries: [entry], count: 1 });
assert.deepEqual(await (await expanded.appRequest('replacement', '/api/entries')).json(), entries);
assert.equal((await expanded.api('/v1/admin')).capacity.slots.available, 0);
await assert.rejects(exec(process.execPath, [cli, ...args], { env: operator, timeout: 900000 }), error => /already has containers/.test(error.stderr));
assert.ok((await projectContainers(operator.COMPOSE_PROJECT_NAME)).every(c => !c.State.Running));
console.log('PASS: expansion preserves both apps and authority, approves isolated third-app state, refuses fourth-app capacity, and survives gateway/replica restart');

async function ready(current) {
  await expect.poll(async () => { try { return (await current.appRequest('accounts', '/')).status; } catch { return 0; } }, { timeout: 120000 }).toBe(200);
  await expect.poll(async () => { try { return (await current.appRequest('replacement', '/api/entries')).status; } catch { return 0; } }, { timeout: 120000 }).toBe(200);
}
