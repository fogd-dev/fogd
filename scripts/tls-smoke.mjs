import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { createHash, X509Certificate, randomBytes } from 'node:crypto';
import { join, resolve } from 'node:path';
import { platformClient } from './platform-client.mjs';
import { accountsBrowser } from './accounts-browser.mjs';
import { expect } from './guestbook-browser.mjs';
import { compose, stackRoot, run } from '../packages/cli/src/local.mjs';

const client = await platformClient();
assert.equal(client.env.FOGD_PROFILE, 'shared'); assert.equal(client.env.FOGD_TLS, '1');
assert.equal(client.env.FOGD_DEPLOY_TOKEN, '');
const cli = join(stackRoot, 'packages/cli/bin/fogd.js');
let state;
await expect.poll(async () => { try { state = await client.api('/v1/admin'); return true; } catch { return false; } }, { timeout: 60000 }).toBe(true);
assert.equal(Object.keys(state.apps).length, 0, 'Use a fresh TLS stack');
const untrustedEnv = { ...client.env }; delete untrustedEnv.NODE_EXTRA_CA_CERTS;
const untrusted = spawnSync(process.execPath, [cli, 'admin', 'list'], { env: untrustedEnv, encoding: 'utf8', timeout: 30000 });
assert.notEqual(untrusted.status, 0, 'Untrusted certificate must be refused');
assert.match(untrusted.stderr, /fetch failed|certificate/i);
let plaintext;
try { plaintext = await fetch(`http://127.0.0.1:${client.env.FOGD_ADMIN_PORT || 8788}/v1/admin`); } catch {}
assert.ok(!plaintext?.ok);
assert.equal((await client.api('/v1/admin')).credentials.length, 0);
const token = JSON.parse(await run(process.execPath, [cli, 'admin', 'issue-token', 'TLS builder', 'accounts'], { env: client.env, capture: true }));
await run(process.execPath, [cli, 'deploy'], { cwd: join(stackRoot, 'examples/accounts'), env: { ...client.env, FOGD_DEPLOY_TOKEN: token.token } });
const release = Object.values((await client.api('/v1/admin')).deployments)[0];
const secretInput = JSON.stringify({ BETTER_AUTH_SECRET: randomBytes(32).toString('hex') });
const secret = spawnSync(process.execPath, [cli, 'admin', 'secrets', 'accounts'], { env: client.env, input: secretInput, encoding: 'utf8', timeout: 30000 });
assert.equal(secret.status, 0, 'Secret configuration failed');
const revision = JSON.parse(secret.stdout).revision;
const approved = JSON.parse(await run(process.execPath, [cli, 'admin', 'approve', release.id, release.digest, revision], { env: client.env, capture: true }));
assert.equal(approved.status, 'active');
const origin = client.env.FOGD_SERVER || `https://127.0.0.1:${client.env.FOGD_ADMIN_PORT || 8788}`;
assert.equal((await fetch(origin + '/internal/route?host=accounts.localhost', { headers: { Authorization: `Bearer ${client.env.FOGD_GATEWAY_TOKEN}` } })).status, 404);
const cert = new X509Certificate(await readFile(resolve(process.argv[2] || '.fogd/m8b2-cert/server.pem')));
const pin = createHash('sha256').update(cert.publicKey.export({ type: 'spki', format: 'der' })).digest('base64');
const account = await accountsBrowser(client.browserURL('accounts'), `tls-${Date.now()}@example.test`, 'TLS account password', { args: [`--ignore-certificate-errors-spki-list=${pin}`] });
try {
  await account.enroll();
  const cookies = await account.context.cookies();
  assert.ok(cookies.some(c => c.secure && c.httpOnly), 'Session cookie must be Secure and HttpOnly');
  await account.context.setExtraHTTPHeaders({ 'x-forwarded-proto': 'http', 'x-forwarded-host': 'evil.example', forwarded: 'host=evil.example;proto=http' });
  const absolute = await account.page.evaluate(async () => (await fetch('/api/origin')).json());
  assert.equal(absolute.privateURL, new URL('/api/private', client.browserURL('accounts')).href);
  const project = client.env.COMPOSE_PROJECT_NAME;
  assert.ok(project, 'Use an explicit TLS test project');
  const bundle = join(stackRoot, '.fogd', `${project}-tls-backup`);
  const output = join(stackRoot, '.fogd', `${project}-tls-restore`);
  await run(process.execPath, [cli, 'backup', bundle], { env: client.env });
  await run(process.execPath, [cli, 'restore', bundle, '--project', `${project}-restore`, '--output', output], { env: client.env });
  await compose(['up', '-d', '--pull', 'never'], { ...client.env, COMPOSE_PROJECT_NAME: `${project}-restore`, FOGD_COMPOSE_FILE: join(output, 'compose.json') });
  await expect.poll(async () => { try { return (await client.appRequest('accounts', '/')).status; } catch { return 0; } }, { timeout: 120000 }).toBe(200);
  await account.ready('Session active');
  assert.equal((await client.api('/v1/admin')).secrets.accounts.revision, revision);
  const status = JSON.parse(await run(process.execPath, [cli, 'status', release.id], { env: { ...client.env, FOGD_DEPLOY_TOKEN: token.token }, capture: true }));
  assert.equal(status.status, 'active');
  await account.signOut(); await account.signIn(); await account.signedIn();
  const untrustedRestore = spawnSync(process.execPath, [cli, 'admin', 'list'], { env: untrustedEnv, encoding: 'utf8', timeout: 30000 });
  assert.notEqual(untrustedRestore.status, 0);
} finally { await account.browser.close(); }
console.log('PASS: trusted HTTPS CLI deployment and approval, untrusted CA refusal, private routing boundary, native Secure sessions, forwarding-spoof rejection, TLS/scoped credential/session recovery');
