import assert from 'node:assert/strict';
import { runtimeFamily } from '../../packages/cli/src/runtime/catalog.mjs';
import { selectedHostTrial } from '../cron-probe/selected/selected-trial.mjs';
import { selectedHostOptions } from '../cron-probe/selected/options.mjs';
import { pendingLifecycle, inertBackgroundMinute, approveLifecycle, controllerHeldMinute, snapshotBackground } from '../cron-probe/selected/background-lifecycle.mjs';
import { compatibleBackgroundUpdate, nativeBackgroundRetry, scheduledWorkWhileHTTPPaused, queuedWorkWhileHTTPPaused } from '../cron-probe/selected/background-update.mjs';
import { setFaultPolicy, vmTime } from '../cron-probe/selected/observations.mjs';
import { resumeCron, futurePhase } from '../cron-probe/selected/recovery-work.mjs';
import { queuedInput, completeQueuedInput } from '../cron-probe/selected/retirement-steps.mjs';
import { selectedNoRetry } from '../cron-probe/selected/failure-scheduled-cases.mjs';
import { scanPublicSurfaces } from '../cron-probe/selected/privacy.mjs';

const options = selectedHostOptions(process.argv.slice(2));
assert.equal(runtimeFamily(options.hostOptions.runtime, 'enrolled').routing, 'durable', 'Background lifecycle qualification requires an explicit durable family');
await selectedHostTrial(options.output, 'Fresh native queue and cron lifecycle on the selected durable candidate: inert scoped upload, exact secret approval, autonomous work, noRetry, compatible SQL/cadence update, original-occurrence retry, persisted pause and serving through controller loss, HTTP/dispatch separation and a verified stopped durable snapshot. No restore, retirement, owner-loss, terminal retry-ceiling, power-loss or complete family-admission qualification.', async context => {
  const { source: host, evidence } = context, fixture = await pendingLifecycle(host);
  context.phase = 'unapproved-minute'; evidence.unapproved = await inertBackgroundMinute(host, fixture);
  context.phase = 'exact-approval'; evidence.approvals = await approveLifecycle(host, fixture);
  context.phase = 'queued-baseline';
  const baseline = await queuedInput(host, fixture.request, fixture.approvals.imports, 'baseline-input', 'apple\npear', ['APPLE', 'PEAR']);
  evidence.queueBaseline = await completeQueuedInput(host, fixture.approvals.imports, baseline);
  context.phase = 'autonomous-baseline';
  const initial = fixture.approvals.refresh;
  await setFaultPolicy(host, initial.slot, initial.id, 'healthy', 'snapshot-a');
  evidence.initialResume = await resumeCron(host, initial);
  evidence.initialWork = await futurePhase(host, initial, 'snapshot-a', evidence.initialResume.requestedAt);
  context.phase = 'native-no-retry'; evidence.noRetry = {};
  await selectedNoRetry({ host, active: initial, clock: () => vmTime(host), evidence: evidence.noRetry });
  context.phase = 'compatible-update'; evidence.update = await compatibleBackgroundUpdate(host, fixture);
  context.phase = 'native-original-occurrence-retry'; evidence.retry = await nativeBackgroundRetry(host, fixture.approvals.refresh);
  context.phase = 'paused-controller-loss'; evidence.controllerLoss = await controllerHeldMinute(host, fixture);
  context.phase = 'explicit-queued-resume';
  evidence.queueAfterRestart = await completeQueuedInput(host, fixture.approvals.imports, { id: 'held-input', labels: ['KIWI', 'LIME'] });
  context.phase = 'scheduled-work-with-http-paused'; evidence.httpPause = await scheduledWorkWhileHTTPPaused(host, fixture);
  context.phase = 'queued-work-with-http-paused'; evidence.queueHTTPPause = await queuedWorkWhileHTTPPaused(host, fixture);
  context.phase = 'privacy'; evidence.privacy = {};
  for (const app of ['refresh', 'imports']) evidence.privacy[app] = await scanPublicSurfaces(host, fixture.request, fixture.submissions[app], fixture.tokens[app], [fixture.secret], evidence);
  context.phase = 'stopped-durable-snapshot'; evidence.snapshot = await snapshotBackground(host, fixture);
  return fixture;
}, options.enrollment, options.hostOptions);
