// Retire a canonical queue app, preserve its bytes, and approve a replacement independently.
import assert from 'node:assert/strict';
import { createHash, randomUUID } from 'node:crypto';
import { join } from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { context } from './queue-probe/context.mjs';
import { prefixFingerprints } from './queue-probe/prefix-fingerprints.mjs';
import { expect } from './guestbook-browser.mjs';
import { request } from './http.mjs';
import { stackRoot, run } from '../packages/cli/src/local.mjs';
import { execute } from '../packages/cli/src/recovery/execute.mjs';
import { backup } from '../packages/cli/src/recovery/backup.mjs';
import { composeArgs } from '../packages/cli/src/recovery/docker.mjs';

const [output, target] = process.argv.slice(2);
assert.match(target || '', /^fogd-m11[a-z0-9-]*$/);
const probe = await context('slot-1', output, { queueName: 'imports-public-imports' });
assert.notEqual(target, probe.config.name);
const app = 'imports-public', neighbor = 'imports-claim', replacement = 'imports-next';
let env = probe.env;
const cli = args => execute(process.execPath, [join(stackRoot, 'packages/cli/bin/fogd.js'), ...args], { env });
const auth = { Authorization: `Basic ${Buffer.from(`${env.FOGD_ADMIN_USER}:${env.FOGD_ADMIN_PASSWORD}`).toString('base64')}` };
async function admin() { const r = await fetch(`http://127.0.0.1:${env.FOGD_ADMIN_PORT}/v1/admin`, { headers: auth }); assert.equal(r.status, 200); return r.json(); }
const gateway = (name, path, options = {}) => request(`http://127.0.0.1:${env.FOGD_HTTP_PORT}${path}`, { ...options, headers: { Host: `${name}.localhost`, 'Content-Type': 'application/json' } });
const state = await admin(), active = state.deployments[state.apps[app].active];
assert.equal(state.apps[app].slot, probe.slot.id);
assert.equal(state.apps[neighbor].route, 'active');
assert.ok(!state.apps[neighbor].resources?.queues); assert.notEqual(state.apps[neighbor].slot, probe.slot.id);
const priorNeighbor = await gateway(neighbor, '/api/posts'); assert.equal(priorNeighbor.status, 200);
const neighborRows = await priorNeighbor.json(); assert.ok(neighborRows.length > 0);
await cli(['admin', 'delivery', app, 'pause']);
assert.equal((await probe.queue('info')).backlogCount, 0);
const id = `retire-${randomUUID()}`;
const accepted = await gateway(app, '/api/imports', { method: 'POST', body: JSON.stringify({ id, text: 'retained\ncanonical' }) });
assert.equal(accepted.status, 202);
const bundle = join(probe.output, 'snapshot'), destination = join(probe.output, 'retired');
const manifest = await backup(bundle);
assert.equal(manifest.queueRecovery.apps[app].observation.backlogCount, 1);
await probe.compose(['up', '-d', '--no-deps', 'minio']);
let fingerprints;
try { fingerprints = await prefixFingerprints(probe.compose, probe.slot.prefix, false); assert.ok(fingerprints.length > 0); }
finally { await probe.compose(['stop', 'minio']); }
await probe.save('source-prefix', fingerprints);
await probe.compose(['down']);
await cli(['retire', bundle, '--app', app, '--digest', active.digest, '--project', target, '--output', destination, '--stop-queued-work']);
env = { ...env, FOGD_COMPOSE_FILE: join(destination, 'compose.json'), COMPOSE_PROJECT_NAME: target };
const restoredConfig = JSON.parse(await readFile(env.FOGD_COMPOSE_FILE));
const replacementPrefix = JSON.parse(restoredConfig.services.controller.environment.FOGD_SLOTS).find(s => s.id === probe.slot.id).prefix;
assert.notEqual(replacementPrefix, probe.slot.prefix); assert.match(replacementPrefix, /^retirement-generations\//);
const compose = args => execute('docker', [...composeArgs(env.FOGD_COMPOSE_FILE, target), ...args]);
await compose(['up', '-d', '--pull', 'never']);
await expect.poll(async () => { try { return (await admin()).apps[app].route; } catch { return null; } }, { timeout: 120000 }).toBe('retired');
const retired = (await admin()).apps[app];
assert.equal(retired.delivery, undefined); assert.equal(retired.retirement.queue.snapshot.backlogCount, 1);
await expect.poll(async () => (await gateway(neighbor, '/api/posts')).status, { timeout: 120000 }).toBe(200);
assert.equal((await gateway(app, '/api/imports')).status, 404);
assert.deepEqual(await (await gateway(neighbor, '/api/posts')).json(), neighborRows);
assert.deepEqual(await prefixFingerprints(compose, probe.slot.prefix, true), fingerprints);
const credential = JSON.parse(await cli(['admin', 'issue-token', 'queue-retirement-replacement', replacement]));
const before = await admin();
const log = await run(process.execPath, [join(stackRoot, 'packages/cli/bin/fogd.js'), 'deploy', '--name', replacement], { cwd: join(stackRoot, 'examples/hello'), env: { ...env, FOGD_DEPLOY_TOKEN: credential.token }, capture: true });
await writeFile(join(probe.output, 'replacement-deploy.log'), log, { mode: 0o600 });
const added = Object.values((await admin()).deployments).filter(r => !Object.hasOwn(before.deployments, r.id)); assert.equal(added.length, 1); assert.equal(added[0].app, replacement); assert.equal(added[0].status, 'pending');
await cli(['admin', 'approve', added[0].id, added[0].digest]);
assert.equal((await admin()).apps[replacement].slot, probe.slot.id);
const served = await gateway(replacement, '/api/posts'); assert.equal(served.status, 200);
assert.equal((await gateway(app, '/api/imports')).status, 404);
const finalFingerprints = await prefixFingerprints(compose, probe.slot.prefix, true);
assert.deepEqual(finalFingerprints, fingerprints);
const retainedPrefixDigest = createHash('sha256').update(JSON.stringify(finalFingerprints)).digest('hex');
assert.deepEqual(await (await gateway(neighbor, '/api/posts')).json(), neighborRows);
await probe.save('retirement', { source: probe.config.name, target, app, active: { id: active.id, digest: active.digest }, pendingJob: id, retainedPrefix: probe.slot.prefix, retainedObjects: fingerprints.length, retainedPrefixDigest, replacementPrefix, retirement: retired.retirement, neighbor: { app: neighbor, rows: neighborRows }, replacement: { app: replacement, id: added[0].id, digest: added[0].digest, rows: await served.json() } });
console.log('PASS: canonical queued retirement preserves retained bytes and neighboring app; ordinary approved replacement uses the released fleet');
