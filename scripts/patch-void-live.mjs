// Regenerate the published JS file from the separately reviewed upstream TS patch.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join, dirname, resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { transformWithOxc } from 'vite';
const [sourcePath, packageDir] = process.argv.slice(2);
assert.ok(sourcePath && packageDir, 'Supply patched live-server.ts and an extracted void package directory');
assert.equal(JSON.parse(await readFile(join(packageDir, 'package.json'), 'utf8')).version, '1.1.11');
const git = args => execFileSync('git', ['-C', dirname(resolve(sourcePath)), ...args], { encoding: 'utf8' }).trimEnd();
const root = git(['rev-parse', '--show-toplevel']);
assert.equal(resolve(sourcePath), join(root, 'packages/void/src/runtime/live-server.ts'));
assert.equal(git(['rev-parse', 'HEAD']), '6ef71cfe1b3364e04fd0ec261f7f00bef6aeb99f');
const status = git(['status', '--porcelain', '--untracked-files=no']).split('\n').filter(Boolean);
assert.deepEqual(status.map(line => line.slice(3)), ['packages/void/src/runtime/live-server.ts']);
const normalize = patch => patch.replace(/^index .*\n/gm, '').trimEnd();
const expected = await readFile(new URL('../patches/void-1.1.11-live-registration.patch', import.meta.url), 'utf8');
assert.ok(normalize(git(['diff', 'HEAD', '--', ':(top)packages/void/src/runtime/live-server.ts'])) === normalize(expected), 'Source differs from reviewed patch');
const target = join(packageDir, 'dist/runtime/live-server.mjs');
const original = await readFile(target, 'utf8');
const imports = original.split('\n').filter(line => line.startsWith('import ')).join('\n');
assert.equal(imports.split('\n').length, 2);
assert.ok(imports.includes('eventStream') && imports.includes('__getLiveBindingName'));
const source = await readFile(sourcePath, 'utf8');
assert.ok(source.includes('private nextSubscriptionRevision') && source.includes('private enqueueRegister'));
const transformed = await transformWithOxc(source, 'live-server.ts');
const names = text => new Set([...text.matchAll(/import\s*\{([^}]+)\}/g)].flatMap(match => match[1].split(',').map(name => name.trim().split(/\s+as\s+/).at(-1)).filter(Boolean)));
const supplied = names(imports);
for (const name of names(transformed.code)) assert.ok(supplied.has(name), `Missing packaged import: ${name}`);
const code = transformed.code.replace(/^import[\s\S]*?from ['"][^'"]+['"];\n/gm, '');
await writeFile(target, `${imports}\n${code}`);
console.log('Generated void@1.1.11 live-server.mjs with existing packaged runtime imports');
