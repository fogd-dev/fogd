import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { setTimeout } from 'node:timers/promises';
import { context } from './queue-probe/context.mjs';
import { expect } from './guestbook-browser.mjs';
import { stackRoot, run } from '../packages/cli/src/local.mjs';
import { projectContainers } from '../packages/cli/src/recovery/docker.mjs';

const [slotId, outputArg, target] = process.argv.slice(2);
assert.ok(outputArg); assert.match(target || '', /^fogd-m11[a-z0-9-]*$/);
const output = resolve(outputArg); await mkdir(output, { mode: 0o700 });
const source = await context(slotId, join(output, 'before'));
assert.notEqual(target, source.config.name);
for (const slot of source.slots) assert.equal((await source.queue('pause', slot)).paused, true);
assert.equal((await source.queue('info')).stored, 0);
await source.queue('resume');
await source.app({ id: 'recover-held', holdMs: source.budget * 600 });
await expect.poll(async () => (await source.app()).some(e => e.job === 'recover-held' && e.stage === 'started'), { timeout: 120000 }).toBe(true);
await source.queue('pause');
await source.app({ id: 'recover-pending' });
const leases = JSON.parse((await source.cli(['queue', 'peek', 'probe-jobs', '--json'])).trim()).messages.filter(m => m.state === 'leased');
assert.equal(leases.length, 1);
const leaseExpiresAt = leases[0].leasedUntil;
assert.ok(Number.isFinite(leaseExpiresAt));
const before = await source.app();
assert.ok(!before.some(e => e.job === 'recover-held' && e.stage === 'completed'));
await source.compose(['stop', '-t', '0', ...source.slot.nodes]);
await source.save('events', before);
const cli = join(stackRoot, 'packages/cli/bin/fogd.js'), bundle = join(output, 'snapshot'), restoredDir = join(output, 'restored');
await run(process.execPath, [cli, 'backup', bundle], { env: source.env });
await run(process.execPath, [cli, 'restore', bundle, '--project', target, '--output', restoredDir], { env: source.env });
const env = { ...source.env, COMPOSE_PROJECT_NAME: target, FOGD_COMPOSE_FILE: join(restoredDir, 'compose.json') };
await run(process.execPath, [cli, 'up'], { env });
const restored = await context(slotId, join(output, 'after'), env);
await expect.poll(async () => { try { return (await restored.queue('info')).paused; } catch { return false; } }, { timeout: 120000 }).toBe(true);
for (const slot of restored.slots) assert.equal((await restored.queue('info', slot)).paused, true);
await setTimeout(Math.max(3000, leaseExpiresAt + 1000 - Number(await restored.node('console.log(Date.now())'))));
const observedAt = Number(await restored.node('console.log(Date.now())'));
assert.ok(observedAt > leaseExpiresAt);
const recovered = await restored.app();
assert.deepEqual(recovered, before);
assert.equal((await restored.queue('info')).stored, 2);
await restored.save('paused', { leaseExpiresAt, observedAt, events: recovered, queue: await restored.queue('info') });
await restored.queue('resume');
for (const [job, attempt] of [['recover-pending', 1], ['recover-held', 2]]) await expect.poll(async () => (await restored.app()).some(e => e.job === job && e.stage === 'completed' && e.attempt === attempt), { timeout: 120000 }).toBe(true);
await expect.poll(async () => (await restored.queue('info')).stored, { timeout: 120000 }).toBe(0);
await restored.queue('pause');
await restored.save('resumed', { events: await restored.app(), queue: await restored.queue('info') });
assert.ok((await projectContainers(source.config.name)).every(c => !c.State.Running));
console.log('PASS: paused pending and interrupted work survive stopped full-volume recovery; deliberate resume completes attempts 1 and 2; source stays stopped');
