import assert from 'node:assert/strict';
import { join } from 'node:path';
import { Delivery, initialDelivery } from '../packages/platform/src/delivery.mjs';
import { readJson, saveJson } from '../packages/platform/src/store.mjs';
import { context } from './queue-probe/context.mjs';
import { queueRuntime } from './queue-probe/runtime.mjs';

const [slot, output] = process.argv.slice(2);
const probe = await context(slot, output, { queueName: 'imports' });
const runtime = queueRuntime(probe), path = join(probe.output, 'delivery.json');
const version = (await probe.state())[0].deployment.version;
await saveJson(path, initialDelivery('imports', 'first'));
const options = { slot: probe.slot, runtime, persist: state => saveJson(path, state) };
let delivery = new Delivery({ ...options, state: await readJson(path) });
await delivery.hold('first');
await delivery.pause();
await delivery.completeActivation('first', version);
assert.equal((await runtime.status(probe.slot, 'imports')).paused, true);
await probe.save('operator-paused', delivery.state);
const resume = runtime.resume.bind(runtime);
let resumes = 0;
runtime.resume = async (...args) => { resumes++; await resume(...args); throw Error('Injected lost resume response'); };
await assert.rejects(delivery.resume(), /Injected lost resume response/);
const uncertain = await readJson(path), actual = await runtime.status(probe.slot, 'imports');
assert.equal(uncertain.observed, 'unknown'); assert.equal(uncertain.operation, 'resume'); assert.equal(actual.paused, false);
await probe.save('uncertain', { journal: uncertain, runtime: actual });
delivery = new Delivery({ ...options, state: uncertain });
assert.equal(resumes, 1);
await delivery.observe();
assert.equal(resumes, 1); assert.equal(delivery.state.operation, 'resume');
runtime.resume = async (...args) => { resumes++; return resume(...args); };
await delivery.reconcile();
assert.equal(resumes, 2); assert.equal(delivery.state.observed, 'running'); assert.equal(delivery.state.operation, null);
await probe.save('reconciled', delivery.state);
await delivery.hold('update');
assert.equal(delivery.state.desired, 'running');
await assert.rejects(delivery.resume(), /hold/);
await delivery.pause();
await delivery.completeActivation('update', version);
assert.equal(delivery.state.observed, 'paused'); assert.equal((await runtime.status(probe.slot, 'imports')).paused, true);
await probe.save('final', delivery.state);
console.log('PASS: durable journal preserves operator pause and activation hold, records a lost resume response as unknown, and requires explicit retry after reload');
