import assert from 'node:assert/strict';
import { readFile, access } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { configEnv, stackRoot, run } from '../packages/cli/src/local.mjs';
import { projectContainers } from '../packages/cli/src/recovery/docker.mjs';
import { verifyBundle } from '../packages/cli/src/recovery/bundle.mjs';
import { interruptAfterControllerRestore } from './recovery-fault.mjs';
const exec = promisify(execFile), env = await configEnv();
const bundle = resolve(process.argv[2]), stem = process.argv[3];
assert.match(stem || '', /^fogd-m10[a-z0-9-]*$/);
const snapshot = await verifyBundle(bundle);
assert.ok((await projectContainers(snapshot.manifest.sourceProject)).every(c => !c.State.Running));
const project = `${stem}-interrupted`, output = join(stackRoot, '.fogd', `${project}-config`);
const retry = `${stem}-retry`, retryOutput = join(stackRoot, '.fogd', `${retry}-config`);
const cli = join(stackRoot, 'packages/cli/bin/fogd.js');
const args = ['expand', bundle, '--fleets', '3', '--project', project, '--output', output];
for (const path of [output, retryOutput]) await assert.rejects(access(path), { code: 'ENOENT' });
await interruptAfterControllerRestore({ cli, args, env, project, shim: join(stackRoot, '.fogd', `${stem}-fault-injection`) });
for (const file of ['compose.json', 'restored.json']) await assert.rejects(access(join(output, file)), { code: 'ENOENT' });
assert.ok((await projectContainers(project)).every(c => !c.State.Running));
await assert.rejects(exec(process.execPath, [cli, ...args], { env, timeout: 900000 }), error => /already has containers/.test(error.stderr));
await run(process.execPath, [cli, 'expand', bundle, '--fleets', '3', '--project', retry, '--output', retryOutput], { env });
assert.ok(JSON.parse(await readFile(join(retryOutput, 'restored.json'), 'utf8')).expansion);
assert.ok((await projectContainers(retry)).every(c => !c.State.Running));
console.log('PASS: interrupted expansion publishes no completion files; occupied target refused; fresh retry completes stopped');
