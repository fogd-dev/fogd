// Private Docker qualification; public queue upload admission remains closed.
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { context } from './queue-probe/context.mjs';
import { stackRoot } from '../packages/cli/src/local.mjs';
import { json, composeArgs } from '../packages/cli/src/recovery/docker.mjs';
import { execute } from '../packages/cli/src/recovery/execute.mjs';
import { backup } from '../packages/cli/src/recovery/backup.mjs';
import { retire } from '../packages/cli/src/recovery/retire.mjs';
import { expect } from './guestbook-browser.mjs';
import { request } from './http.mjs';
const [output, target] = process.argv.slice(2);
assert.match(target || '', /^fogd-m11[a-z0-9-]*$/);
const probe = await context('slot-1', output, { queueName: 'imports' });
const [image] = await json(['image', 'inspect', 'fogd-runtime:local']);
const prior = probe.config.services.controller.image;
for (const service of Object.values(probe.config.services)) if (service.image === prior) service.image = image.Id;
await writeFile(probe.env.FOGD_COMPOSE_FILE, JSON.stringify(probe.config, null, 2) + '\n');
await probe.compose(['up', '-d', '--pull', 'never']);
await probe.compose(['stop', 'controller']);
await probe.compose(['run', '--rm', '--no-deps', '-T', '-v', `${join(stackRoot, 'scripts/queue-probe')}:/tmp/qualification:ro`, 'controller', 'node', '/tmp/qualification/retirement-stage.mjs', 'imports', 'survivor']);
await probe.compose(['up', '-d', '--pull', 'never', 'controller']);
const auth = { Authorization: `Basic ${Buffer.from(`${probe.env.FOGD_ADMIN_USER}:${probe.env.FOGD_ADMIN_PASSWORD}`).toString('base64')}` };
const origin = `http://127.0.0.1:${probe.env.FOGD_ADMIN_PORT}`;
async function admin(path = '/v1/admin') { const r = await fetch(origin + path, { headers: auth }); assert.equal(r.status, 200); return r.json(); }
await expect.poll(async () => { try { return (await admin()).apps.survivor?.route; } catch { return null; } }, { timeout: 120000 }).toBe('active');
const jobId = `retire-${Date.now()}`;
const pending = await probe.http('/api/imports', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ id: jobId, text: 'retained\nretired' }) });
assert.equal(pending.status, 202, pending.body);
const state = await admin(), active = state.deployments[state.apps.imports.active];
const bundle = join(probe.output, 'snapshot'), destination = join(probe.output, 'restored');
const manifest = await backup(bundle);
assert.deepEqual(Object.keys(manifest.queueRecovery.apps).sort(), ['imports', 'survivor']);
await retire(bundle, 'imports', active.digest, target, destination, true);
const command = composeArgs(join(destination, 'compose.json'), target);
const compose = args => execute('docker', [...command, ...args]);
await compose(['up', '-d', '--pull', 'never']);
await expect.poll(async () => { try { return (await admin()).apps.imports?.route; } catch { return null; } }, { timeout: 120000 }).toBe('retired');
const restored = await admin();
assert.equal(restored.apps.imports.delivery, undefined);
assert.equal(restored.apps.survivor.queueRecovery.status, 'pending');
assert.equal(restored.apps.survivor.route, 'paused');
assert.equal((await request(`http://127.0.0.1:${probe.env.FOGD_HTTP_PORT}/api/imports`, { headers: { Host: 'imports.localhost' } })).status, 404);
const config = JSON.parse(await readFile(join(destination, 'compose.json')));
const slots = JSON.parse(config.services.controller.environment.FOGD_SLOTS);
assert.notEqual(slots[0].prefix, probe.slot.prefix);
assert.equal(slots[1].prefix, probe.slots[1].prefix);
await probe.save('retirement', { source: probe.config.name, target, image: image.Id, jobId, retired: restored.apps.imports, survivor: restored.apps.survivor.queueRecovery, replacementPrefix: slots[0].prefix });
console.log('PASS: retired route removed, fresh prefix assigned, survivor recovery remains pending');
