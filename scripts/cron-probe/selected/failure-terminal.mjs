import assert from 'node:assert/strict';
import { selectedTrial } from './selected-trial.mjs';
import { selectedHostOptions } from './options.mjs';
import { privateFaultProject, importJob, backgroundCredentials, approveRefresh, approveImports } from './background-fixtures.mjs';
import { negotiatedCapabilities } from './offline-build.mjs';
import { scopedClient } from './https.mjs';
import { localTerminalBuild } from './terminal-build.mjs';
import { selectedTerminal } from './failure-scheduled-cases.mjs';
import { pauseFailureWork } from './failure-phases.mjs';
import { nativeObservation, vmTime } from './observations.mjs';
import { nativeProcesses } from './recovery-fence.mjs';
import { verifiedObservationKeys } from './failure-authority.mjs';
import { rows } from './recovery-ledger.mjs';
import { waitFor } from './https.mjs';
import { scanPublicSurfaces } from './privacy.mjs';
import { stopSelectedHost } from './shutdown.mjs';

const options = selectedHostOptions(process.argv.slice(2));
await selectedTrial(options.output, 'Fresh v5 native sparse cron terminal retry ceiling: recorded local buildArtifact output, six counted attempts per job with native backoff, future natural wake, corrected future success and no replay of the failed occurrence. Peer queue records and native process identities remain unchanged. No network-isolated build claim.', async context => {
  const { source: host, evidence } = context;
  assert.equal(host.entry.routing, 'durable');
  const project = await privateFaultProject(host, 'terminal-sparse-source', '*/3 * * * *');
  const fixture = await backgroundCredentials(host), build = await localTerminalBuild(host, project, await negotiatedCapabilities(host, fixture.tokens.refresh));
  const submit = await scopedClient(host, fixture.tokens.refresh), response = await submit('/v1/deployments', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(build.payload) });
  assert.equal(response.status, 201); const submitted = response.json(); assert.equal(submitted.digest, build.payload.digest);
  const active = await approveRefresh(host, submitted, fixture.secret), imported = await approveImports(host, fixture.tokens.imports);
  fixture.approvals = { refresh: active, imports: imported }; fixture.submissions = { refresh: [active], imports: [imported] };
  evidence.approvals = fixture.approvals; evidence.build = build.verification;
  const configured = await fixture.request('/api/refresh', { app: 'refresh', method: 'POST', headers: { Origin: `https://refresh.localhost:${host.gatewayPort}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ mode: 'healthy' }) });
  assert.equal(configured.status, 200); assert.deepEqual(configured.json(), { mode: 'healthy' });
  host.nativeBaseline = await nativeProcesses(host);
  const clock = () => vmTime(host, host.policy.fleets[1].nodes[0].host);
  await importJob(fixture.request, 'terminal-control', 'kiwi\nlime');
  evidence.untouchedBefore = await waitFor('completed peer queue records', async () => {
    const observed = await nativeObservation(host, imported.slot, imported.id, { persistedRecords: true, captureProofs: true });
    return rows(observed, 'import_jobs').some(row => row.id === 'terminal-control' && row.status === 'complete') && rows(observed, 'import_results').filter(row => row.job_id === 'terminal-control').length === 2 && observed;
  });
  evidence.cronBefore = await nativeObservation(host, active.slot, active.id, { persistedRecords: true, captureProofs: true });
  context.phase = 'sparse-terminal-retry-ceiling'; evidence.terminal = {};
  await selectedTerminal({ host, active, clock, defaults: evidence.defaults, evidence: evidence.terminal });
  context.phase = 'final-pause-and-peer-audit';
  evidence.finalPause = await pauseFailureWork(host, active, clock);
  evidence.final = await nativeObservation(host, active.slot, active.id, { persistedRecords: true, captureProofs: true });
  evidence.untouchedAfter = await nativeObservation(host, imported.slot, imported.id, { persistedRecords: true, captureProofs: true });
  assert.deepEqual(evidence.untouchedAfter.databases, evidence.untouchedBefore.databases);
  assert.deepEqual(verifiedObservationKeys(host.policy, imported.slot, evidence.untouchedAfter), verifiedObservationKeys(host.policy, imported.slot, evidence.untouchedBefore));
  assert.deepEqual(verifiedObservationKeys(host.policy, active.slot, evidence.final), verifiedObservationKeys(host.policy, active.slot, evidence.cronBefore));
  evidence.finalProcesses = await nativeProcesses(host); assert.deepEqual(evidence.finalProcesses, host.nativeBaseline);
  evidence.privacy = [];
  for (const app of ['refresh', 'imports']) evidence.privacy.push(await scanPublicSurfaces(host, fixture.request, fixture.submissions[app], fixture.tokens[app], [fixture.secret], evidence));
  context.phase = 'clean-shutdown'; evidence.shutdown = await stopSelectedHost(host); host.closed = true;
  return fixture;
}, options.enrollment, options.hostOptions);
